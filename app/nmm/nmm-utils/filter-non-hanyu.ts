function removeLoneSurrogatesRegex(str: string) {
  // Remove any high surrogate not followed by a low surrogate
  // and any low surrogate not preceded by a high surrogate
  return str
    .replace(/[\uD800-\uDBFF](?![\uDC00-\uDFFF])/g, "")
    .replace(/(?<![\uD800-\uDBFF])[\uDC00-\uDFFF]/g, "");
}

function isSurrogate(str: string) {
  return removeLoneSurrogatesRegex(str) === "";
}

export const filterNonHanYu = (hanzi: string): boolean =>
  !nonHanYuChars?.includes(hanzi?.toLowerCase()) && !isSurrogate(hanzi);
