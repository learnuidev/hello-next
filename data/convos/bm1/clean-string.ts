"use client";

export const cleanString = (str: string) => {
  return str
    ?.split("")
    ?.filter(Boolean)
    .join("")
    ?.trim()
    ?.replaceAll("？", "")
    ?.replaceAll("！", "")
    ?.replaceAll("！ ", "")
    ?.replaceAll(" ", "")
    ?.replaceAll("，", "")
    ?.replaceAll("。", "")
    ?.replaceAll("!", "")
    ?.replaceAll(" ", "")
    ?.replaceAll(",", "")
    ?.replaceAll(".", "")
    ?.replaceAll("?", "")
    ?.replaceAll("…", "")
    ?.replaceAll("Cindy", "")
    ?.replaceAll("：", "")
    ?.replaceAll(":", "")
    ?.replaceAll("：", "")
    ?.replaceAll("、", "")
    ?.replaceAll("（", "")
    ?.replaceAll("）", "")
    ?.replaceAll("，", "")
    ?.replaceAll("：", "")
    ?.replaceAll("a", "")
    ?.replaceAll("b", "")
    ?.replaceAll("c", "")
    ?.replaceAll("d", "")
    ?.replaceAll("e", "")
    ?.replaceAll("f", "")
    ?.replaceAll("g", "")
    ?.replaceAll("h", "")
    ?.replaceAll("i", "")
    ?.replaceAll("j", "")
    ?.replaceAll("k", "")
    ?.replaceAll("l", "")
    ?.replaceAll("m", "")
    ?.replaceAll("n", "")
    ?.replaceAll("p", "")
    ?.replaceAll("q", "")
    ?.replaceAll("r", "")
    ?.replaceAll("s", "")
    ?.replaceAll("t", "")
    ?.replaceAll("u", "")
    ?.replaceAll("v", "")
    ?.replaceAll("w", "")
    ?.replaceAll("x", "")
    ?.replaceAll("y", "")
    ?.replaceAll("x", "");
};
